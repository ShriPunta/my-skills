const USAGE = 'Usage: node overview-index.mjs [--root DIR | --all] [--check] [--validate] [--stale [--strict] [--base REF]]';
const HOME_MSG = 'Not in a git repository and the current folder is your home folder; refusing to search it. Pass --root DIR.';

function parseArgs(argv) {
  const opts = { root: null, all: false, check: false, stale: false, validate: false, strict: false, base: null, help: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--root') { opts.root = argv[++i]; if (!opts.root) throw new Error('--root needs a folder'); }
    else if (a.startsWith('--root=')) opts.root = a.slice(7);
    else if (a === '--base') { opts.base = argv[++i]; if (!opts.base) throw new Error('--base needs a git ref'); }
    else if (a.startsWith('--base=')) opts.base = a.slice(7);
    else if (a === '--all') opts.all = true;
    else if (a === '--check') opts.check = true;
    else if (a === '--stale') opts.stale = true;
    else if (a === '--validate') opts.validate = true;
    else if (a === '--strict') opts.strict = true;
    else if (a === '-h' || a === '--help') opts.help = true;
    else throw new Error(`unknown argument: ${a}`);
  }
  if (opts.root && opts.all) throw new Error('use either --root or --all, not both');
  if ((opts.strict || opts.base) && !opts.stale) throw new Error('--strict and --base require --stale');
  return opts;
}

/** Short fix command: cwd-relative paths when they stay inside cwd, else the script basename / repo-relative root. */
function fixCommand(ctx, root) {
  const inside = (p) => p && !p.startsWith('..') && !p.startsWith('/');
  const s = toPosix(relative(ctx.cwd, ctx.script));
  const r = toPosix(relative(ctx.cwd, root)) || '.';
  return `node ${inside(s) ? s : basename(ctx.script)} --root ${inside(r) || r === '.' ? r : toPosix(relative(ctx.repoRoot, root)) || '.'}`;
}

function runRoot(root, opts, ctx) {
  const { repoRoot, out, err } = ctx;
  const rootRel = toPosix(relative(repoRoot, root)) || '.';
  const report = (label, list) => {
    if (!list.length) return;
    err(`${label}:`);
    for (const m of list) err(`  - ${m}`);
  };
  if (!existsSync(root)) {
    err(`No overview found at ${rootRel}. Set one up with the setup-repo-overview skill, or pass --root.`);
    return 1;
  }

  const configPath = join(root, 'overview.config.json');
  let configText = '';
  let cfg;
  try {
    let raw = {};
    if (existsSync(configPath)) {
      configText = normalize(readFileSync(configPath, 'utf8'));
      try { raw = JSON.parse(configText); } catch (e) { throw new Error(`${rootRel}/overview.config.json: ${e.message}`); }
    }
    cfg = resolveConfig(raw);
  } catch (e) {
    err(e.message);
    return 1;
  }

  const { docs, errors } = loadDocs(root, { config: cfg });
  const problems = [
    ...REQUIRED_CORE.filter((f) => !existsSync(join(root, f))).map((f) => `${f}: required core file is missing`),
    ...validateDocs(docs, { repoRoot, config: cfg, configText }),
  ];
  const todos = countAuthorTodos(docs);
  const index = buildIndex(docs, { config: cfg });
  const indexPath = join(root, 'INDEX.md');
  const warnings = indexFieldWarnings(docs, { config: cfg });
  const size = Buffer.byteLength(index);
  if (cfg.indexBudgetBytes && size > cfg.indexBudgetBytes) {
    warnings.push(`INDEX.md is ${size} bytes, over indexBudgetBytes (${cfg.indexBudgetBytes}). Trim summaries, or reduce indexFields or maxKeywords.`);
  }
  const noteTodos = () => {
    const n = todos.reduce((s, x) => s + x.count, 0);
    if (n) err(`${n} author-input items open (TODO(author)): ${todos.map((x) => `${x.rel} (${x.count})`).join(', ')}`);
  };
  let code = 0;

  if (opts.check || opts.validate) {
    report('Errors', [...errors, ...problems]);
    if (errors.length || problems.length) code = 1;
    if (opts.check && !errors.length) {
      const current = existsSync(indexPath) ? readFileSync(indexPath, 'utf8') : null;
      if (!sameIndex(current, index)) {
        err(`${rootRel}/INDEX.md is ${current === null ? 'missing' : 'out of date'}. Fix: ${fixCommand(ctx, root)}`);
        code = 1;
      }
    }
    report('Warnings', warnings);
    noteTodos();
    if (code === 0) out(`Overview OK: ${docs.length} files in ${rootRel}`);
  } else if (!opts.stale) {
    if (errors.length) { report('Errors', errors); return 1; }
    report('Warnings', [...problems, ...warnings]);
    noteTodos();
    if (!existsSync(indexPath) || readFileSync(indexPath, 'utf8') !== index) writeFileSync(indexPath, index);
    out(`Wrote ${rootRel}/INDEX.md (${docs.length} files)`);
  }

  if (opts.stale) {
    if (!opts.check && !opts.validate) report('Errors', errors);
    const res = findStale(docs, { repoRoot, excludeRoots: [root, ...ctx.allRoots], staleIgnore: cfg.staleIgnore, mergeBase: ctx.mergeBase });
    const reconfirm = findReconfirm(docs, { days: cfg.reconfirmAfterDays });
    if (res.shallow) err('Warning: shallow clone; history is truncated, so staleness may be missed. Fetch full history (git fetch --unshallow) for accurate results.');
    if (!res.git) {
      out('Not a git repository: staleness check skipped.');
    } else if (!res.stale.length) {
      out('No stale overview files.');
    } else {
      out(ctx.mergeBase
        ? `Possibly stale (code in \`paths\` changed since ${opts.base} with no doc update):`
        : 'Possibly stale (code in `paths` changed after the doc):');
      for (const s of res.stale) {
        const bits = [];
        if (s.commits.length) bits.push(`${s.commits.length} commit(s), newest ${s.commits[0].sha} "${s.commits[0].subject}"`);
        if (s.dirty) bits.push(`${s.dirty} uncommitted file(s)`);
        out(`  - ${s.doc}: ${bits.join('; ')}`);
      }
      if (opts.strict) code = 1;
    }
    if (res.skipped.length) out(`Skipped (doc uncommitted or edited): ${res.skipped.join(', ')}`);
    if (reconfirm.length) {
      out(`Needs reconfirm (author intent not confirmed in ${cfg.reconfirmAfterDays} days):`);
      for (const r of reconfirm) out(`  - ${r.doc}: ${r.confirmed ? `confirmed ${r.confirmed}${r.ageDays === null ? ' (invalid date)' : ` (${r.ageDays} days ago)`}` : 'never confirmed'}`);
    }
  }
  return code;
}

export function main(argv = process.argv.slice(2), cwdIn = process.cwd()) {
  let opts;
  try { opts = parseArgs(argv); } catch (e) { console.error(`${e.message}\n${USAGE}`); return 2; }
  if (opts.help) { console.log(USAGE); return 0; }
  try {
    const cwd = realpathSync(cwdIn);
    const top = git(['rev-parse', '--show-toplevel'], cwd);
    const repoRoot = top ? realpathSync(top) : cwd;
    let atHome = false;
    if (!top) { try { atHome = cwd === realpathSync(homedir()); } catch { /* no home */ } }
    const ctx = { repoRoot, cwd, out: (m) => console.log(m), err: (m) => console.error(m), script: fileURLToPath(import.meta.url), allRoots: [], mergeBase: null };

    let roots;
    if (opts.root) roots = [resolve(cwd, opts.root)];
    else if (opts.all) {
      if (atHome) { console.error(HOME_MSG); return 2; }
      roots = discoverRoots(repoRoot);
      if (!roots.length) { console.error('No overview roots found. Set one up with the setup-repo-overview skill, or pass --root.'); return 1; }
    } else {
      const r = resolveRoot(repoRoot, cwd, { downSearch: !atHome });
      if (r.needRoot) { console.error(HOME_MSG); return 2; }
      if (r.ambiguous) {
        console.error(`Found ${r.ambiguous.length} overview roots; pass --root DIR to pick one or --all for every one:`);
        for (const d of r.ambiguous) console.error(`  - ${toPosix(relative(cwd, d)) || '.'}`);
        return 2;
      }
      roots = [r.root];
    }

    if (opts.stale && top) {
      ctx.allRoots = discoverRoots(repoRoot, { nested: true });
      if (opts.base) {
        if (!git(['rev-parse', '--verify', '--quiet', `${opts.base}^{commit}`], repoRoot)) {
          console.error(`base ref ${opts.base} not found; fetch it (CI: fetch-depth: 0)`);
          return 2;
        }
        ctx.mergeBase = git(['merge-base', opts.base, 'HEAD'], repoRoot);
        if (!ctx.mergeBase) {
          console.error(`no merge base between ${opts.base} and HEAD; fetch full history (CI: fetch-depth: 0)`);
          return 2;
        }
      }
    }

    let code = 0;
    for (const root of roots) {
      if (roots.length > 1) ctx.out(`[${toPosix(relative(repoRoot, root)) || '.'}]`);
      code = Math.max(code, runRoot(root, opts, ctx));
    }
    return code;
  } catch (e) {
    console.error(`overview-index: ${e.message}`);
    return 1;
  }
}

const isMain = (() => {
  try { return import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href; } catch { return false; }
})();
if (isMain) process.exitCode = main();
