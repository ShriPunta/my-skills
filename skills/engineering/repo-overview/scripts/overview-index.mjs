const fmtValue = (v) => asList(v).join(', ');
const oneLine = (s) => String(s).replace(/\s+/g, ' ').trim();

function entry(d, path, fields, maxKeywords) {
  const vals = fields.map((f) => d.data[f]).filter((v) => asList(v).length).map((v) => `\`${oneLine(fmtValue(v))}\``);
  const kw = asList(d.data.keywords).slice(0, maxKeywords);
  const tail = kw.length ? ` _(${kw.join(', ')})_` : '';
  return `- \`${path}\`: ${[...vals, oneLine(d.data.summary)].join(' · ')}${tail}`;
}

/** Build INDEX.md. Pure and deterministic. */
export function buildIndex(docs, { config } = {}) {
  const cfg = resolveConfig(config);
  const byGroup = new Map();
  for (const d of docs) {
    const g = d.group ?? (d.rel.includes('/') ? d.rel.split('/')[0] : '');
    if (!byGroup.has(g)) byGroup.set(g, []);
    byGroup.get(g).push(d);
  }
  const configured = cfg.order.filter((g) => byGroup.has(g));
  const rest = [...byGroup.keys()].filter((g) => g !== '' && !configured.includes(g)).sort(byString);
  const order = [...(byGroup.has('') ? [''] : []), ...configured, ...rest];

  const lines = [GENERATED_HEADER, '', `# ${cfg.title}`, '', INTRO, ''];
  for (const g of order) {
    const fields = asList(cfg.groups[g]?.indexFields);
    const list = [...byGroup.get(g)].sort((a, b) => byString(a.rel, b.rel));
    lines.push(`## ${groupTitle(cfg, g)}`, '', ...list.map((d) => entry(d, d.rel, fields, cfg.maxKeywords)), '');
  }
  return lines.join('\n').trimEnd() + '\n';
}

/** Compare INDEX texts ignoring the first (header) line, CRLF, and trailing whitespace. */
export function sameIndex(a, b) {
  if (a === null || b === null) return false;
  const body = (s) => normalize(s).split('\n').slice(1).join('\n').trimEnd();
  return body(a) === body(b);
}

