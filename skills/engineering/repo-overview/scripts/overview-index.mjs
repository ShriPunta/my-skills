/** Merge user config with defaults. `ignore` adds to the default. Throws on invalid regexes. */
export function resolveConfig(config = {}) {
  if (config && config.__resolved) return config;
  const c = isObj(config) ? config : {};
  const groups = {};
  for (const [k, v] of Object.entries(isObj(c.groups) ? c.groups : {})) groups[k] = isObj(v) ? { ...v } : {};
  const pick = (k) => (c[k] === undefined || c[k] === null ? DEFAULTS[k] : c[k]);
  const deny = asList(c.denyPatterns).map((p) => {
    try { return { source: String(p), re: new RegExp(String(p), 'i') }; } catch (e) { throw new Error(`overview.config.json: invalid denyPatterns entry "${p}": ${e.message}`); }
  });
  return {
    __resolved: true,
    title: pick('title'),
    groups,
    order: Object.keys(groups).filter((g) => g !== ''),
    ignore: [...new Set([...DEFAULTS.ignore, ...asList(c.ignore)])],
    staleIgnore: asList(pick('staleIgnore')),
    reconfirmAfterDays: Number(pick('reconfirmAfterDays')) || 0,
    maxKeywords: Number(pick('maxKeywords')),
    indexBudgetBytes: Number(pick('indexBudgetBytes')) || 0,
    deny,
  };
}

const groupTitle = (cfg, g) => cfg.groups[g]?.title ?? (g === '' ? 'Core' : capitalize(g));

