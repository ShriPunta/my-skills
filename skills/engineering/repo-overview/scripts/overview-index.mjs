function git(args, cwd) {
  try {
    return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trimEnd();
  } catch {
    return null;
  }
}

// ---------------------------------------------------------------------------
// Globs (for `ignore`): `*` within a segment, `**` across segments, `?` one char.
// A pattern without `/` matches the basename at any depth; a trailing `/` matches a folder.
// ---------------------------------------------------------------------------

export function globToRegExp(glob) {
  let re = '';
  for (let i = 0; i < glob.length; i++) {
    const c = glob[i];
    if (c === '*' && glob[i + 1] === '*') {
      if (glob[i + 2] === '/') { re += '(?:.*/)?'; i += 2; } else { re += '.*'; i += 1; }
    } else if (c === '*') re += '[^/]*';
    else if (c === '?') re += '[^/]';
    else re += c.replace(/[.+^${}()|[\]\\]/g, '\\$&');
  }
  return new RegExp(`^${re}$`);
}

export function matchesGlob(rel, pattern) {
  let p = String(pattern).replace(/^\.?\//, '');
  if (p.endsWith('/')) p += '**';
  return p.includes('/') ? globToRegExp(p).test(rel) : globToRegExp(p).test(rel.split('/').pop());
}

// ---------------------------------------------------------------------------
// Frontmatter parser: a small YAML subset.
//   key: value            plain values are taken verbatim (a `#` inside a value is text)
//   "key": 'value'        quoted keys and values
//   key: [a, "b, c"]      inline arrays
//   key:\n  - a           block lists
//   key: > | >- |- >+ |+  block scalars (folded / literal)
//   # comment             full-line comments only
// Nested maps are accepted and ignored (value becomes {}); they never leak into lists.
// ---------------------------------------------------------------------------

function parseQuoted(s, file, ln) {
  const q = s[0];
  const esc = { n: '\n', t: '\t', r: '\r', '0': '\0' };
  let out = '';
  for (let i = 1; i < s.length; i++) {
    const c = s[i];
    if (q === '"' && c === '\\' && i + 1 < s.length) { const n = s[++i]; out += esc[n] ?? n; continue; }
    if (c === q) {
      if (q === "'" && s[i + 1] === "'") { out += "'"; i++; continue; }
      return { value: out, rest: s.slice(i + 1) };
    }
    out += c;
  }
  throw new Error(`${file}:${ln}: unterminated string`);
}

function splitInline(s) {
  const items = [];
  let cur = '';
  let q = null;
  for (const c of s) {
    if (q) { cur += c; if (c === q) q = null; continue; }
    if (c === '"' || c === "'") { q = c; cur += c; continue; }
    if (c === ',') { items.push(cur); cur = ''; continue; }
    cur += c;
  }
  items.push(cur);
  return items.map((x) => x.trim()).filter((x) => x !== '');
}

function parseScalar(raw, file, ln) {
  const s = raw.trim();
  if (s.startsWith('"') || s.startsWith("'")) return parseQuoted(s, file, ln).value;
  return s;
}

function parseValue(raw, file, ln) {
  const s = raw.trim();
  if (s.startsWith('[')) {
    const close = s.lastIndexOf(']');
    if (close < 0) throw new Error(`${file}:${ln}: unterminated inline array`);
    return splitInline(s.slice(1, close)).map((x) => parseScalar(x, file, ln));
  }
  return parseScalar(s, file, ln);
}

function blockScalar(lines, style, chomp) {
  let last = lines.length;
  while (last > 0 && !lines[last - 1].trim()) last--;
  const body = lines.slice(0, last);
  const first = body.find((l) => l.trim());
  const indent = first ? first.length - first.trimStart().length : 0;
  const stripped = body.map((l) => l.slice(Math.min(indent, l.length - l.trimStart().length)));
  let text;
  if (style === '|') {
    text = stripped.join('\n');
  } else {
    text = '';
    let prevBlank = true;
    for (const l of stripped) {
      if (!l.trim()) { text += '\n'; prevBlank = true; continue; }
      text += (prevBlank ? '' : ' ') + l;
      prevBlank = false;
    }
  }
  if (!text) return '';
  if (chomp === '-') return text;
  if (chomp === '+') return text + '\n'.repeat(lines.length - last + 1);
  return text + '\n';
}

const KEY = /^(?:"((?:[^"\\]|\\.)*)"|'((?:[^']|'')*)'|([A-Za-z_][\w.-]*))\s*:(.*)$/;

/** Parse frontmatter. Returns { data, body }. Throws `file:line: message` on bad input or missing summary. */
export function parseFrontmatter(text, file = '<input>') {
  const lines = normalize(text).split('\n');
  if (lines[0].trim() !== '---') throw new Error(`${file}:1: missing frontmatter (file must start with ---)`);
  const end = lines.findIndex((l, i) => i > 0 && l.trim() === '---');
  if (end < 0) throw new Error(`${file}:1: frontmatter is not closed with ---`);

  const data = {};
  const keyLine = {};
  let open = null; // { key, mode: 'pending' | 'list' | 'map', indent }
  for (let i = 1; i < end; i++) {
    const raw = lines[i];
    const ln = i + 1;
    const t = raw.trim();
    if (!t || t.startsWith('#')) continue;
    const indent = raw.length - raw.trimStart().length;
    const item = t.match(/^-(?:\s+(.*))?$/);
    if (open && open.mode === 'pending') {
      if (item) { open.mode = 'list'; open.indent = indent; data[open.key] = []; }
      else if (indent > 0) { open.mode = 'map'; data[open.key] = {}; }
      else open = null;
    }
    if (open && open.mode === 'list') {
      if (item && indent === open.indent) { data[open.key].push(parseScalar(item[1] ?? '', file, ln)); continue; }
      if (indent > open.indent) continue; // continuation of a complex list item: ignored
      open = null;
    }
    if (open && open.mode === 'map') {
      if (indent > 0) continue;
      open = null;
    }
    if (indent > 0) continue; // continuation of a plain scalar: ignored
    if (item) throw new Error(`${file}:${ln}: list item without a key`);
    const kv = raw.match(KEY);
    if (!kv) throw new Error(`${file}:${ln}: cannot parse line: ${t}`);
    const key = kv[1] !== undefined ? kv[1].replace(/\\(.)/g, '$1') : kv[2] !== undefined ? kv[2].replace(/''/g, "'") : kv[3];
    const rest = kv[4].trim();
    keyLine[key] = ln;
    const block = rest.match(/^([|>])([+-]?)$/);
    if (block) {
      let j = i + 1;
      while (j < end && (!lines[j].trim() || /^\s/.test(lines[j]))) j++;
      data[key] = blockScalar(lines.slice(i + 1, j), block[1], block[2]);
      i = j - 1;
    } else if (rest === '') {
      data[key] = '';
      open = { key, mode: 'pending', indent: 0 };
    } else {
      data[key] = parseValue(rest, file, ln);
    }
  }
  if (Array.isArray(data.summary)) throw new Error(`${file}:${keyLine.summary}: summary parsed as a list; quote it`);
  if (typeof data.summary !== 'string' || !data.summary.trim()) {
    throw new Error(`${file}:${keyLine.summary ?? 1}: missing required \`summary\` (one sentence)`);
  }
  return { data, body: lines.slice(end + 1).join('\n') };
}

