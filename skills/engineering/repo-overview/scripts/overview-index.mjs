/**
 * Walk the overview root. Returns { docs: [{rel, group, slug, file, text, data}], errors: [string] }.
 * Skips `_*` and `.*` entries, the root INDEX.md, and `ignore` globs.
 * Follows symlinks safely: broken links are reported, cycles skipped, duplicates deduped by realpath.
 */
export function loadDocs(root, { config } = {}) {
  const cfg = resolveConfig(config);
  const errors = [];
  const found = [];
  const realRoot = realpathSync(root);
  const walk = (dir, relDir, chain) => {
    let real;
    try { real = realpathSync(dir); } catch (e) { errors.push(`${relDir || '.'}: cannot read folder (${e.code || e.message})`); return; }
    if (chain.has(real)) return; // symlink cycle
    const next = new Set(chain).add(real);
    let ents;
    try { ents = readdirSync(dir, { withFileTypes: true }); } catch (e) { errors.push(`${relDir || '.'}: cannot read folder (${e.code || e.message})`); return; }
    ents.sort((a, b) => byString(a.name, b.name));
    for (const ent of ents) {
      const name = ent.name;
      if (name.startsWith('_') || name.startsWith('.')) continue;
      const full = join(dir, name);
      const rel = relDir ? `${relDir}/${name}` : name;
      let isDir = ent.isDirectory();
      let isFile = ent.isFile();
      if (ent.isSymbolicLink()) {
        try { const st = statSync(full); isDir = st.isDirectory(); isFile = st.isFile(); } catch {
          if (name.endsWith('.md')) errors.push(`${rel}: broken symbolic link (target is missing)`);
          continue;
        }
      }
      if (isDir) { walk(full, rel, next); continue; }
      if (!isFile || !name.endsWith('.md')) continue;
      if (rel === 'INDEX.md') continue;
      if (cfg.ignore.some((p) => matchesGlob(rel, p))) continue;
      let realFile;
      let text;
      try { realFile = realpathSync(full); text = readFileSync(full, 'utf8'); } catch (e) { errors.push(`${rel}: cannot read (${e.code || e.message})`); continue; }
      found.push({ rel, full, realFile, text, viaLink: realFile !== join(realRoot, ...rel.split('/')) });
    }
  };
  walk(root, '', new Set());

  // Prefer the canonical (non-symlinked) copy of a file, then the first by path.
  found.sort((a, b) => (a.viaLink - b.viaLink) || byString(a.rel, b.rel));
  const seen = new Set();
  const docs = [];
  for (const f of found) {
    if (seen.has(f.realFile)) continue;
    seen.add(f.realFile);
    const group = f.rel.includes('/') ? f.rel.split('/')[0] : '';
    const slug = group ? f.rel.slice(group.length + 1).replace(/\.md$/, '') : f.rel.replace(/\.md$/, '');
    try {
      docs.push({ rel: f.rel, group, slug, file: f.full, text: f.text, data: parseFrontmatter(f.text, f.rel).data });
    } catch (e) {
      errors.push(e.message);
    }
  }
  docs.sort((a, b) => byString(a.rel, b.rel));
  return { docs, errors };
}

