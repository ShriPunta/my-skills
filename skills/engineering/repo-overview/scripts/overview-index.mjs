/** Existence check for simple globs: checks the longest non-glob directory prefix. */
function pathExists(repoRoot, p) {
  const clean = p.replace(/^\.?\//, '');
  const glob = clean.search(/[*?[]/);
  if (glob < 0) return existsSync(resolve(repoRoot, clean));
  const prefix = clean.slice(0, glob);
  const dir = prefix.includes('/') ? prefix.slice(0, prefix.lastIndexOf('/')) : '.';
  return existsSync(resolve(repoRoot, dir || '.'));
}

/** Markers inside HTML comments (template guidance) are not counted. */
function fillMarkers(text) {
  return [...stripComments(text).matchAll(FILL)].map((m) => `TODO(fill: ${m[1].trim()})`);
}

/** Built-in secret patterns plus config denyPatterns. Reports label and line, never the match. */
export function scanSecrets(text, deny = []) {
  const t = normalize(text);
  const hits = [];
  const seen = new Set();
  const lines = t.split('\n');
  lines.forEach((line, i) => {
    for (const [label, re] of SECRET_PATTERNS) {
      if (re.test(line) && !seen.has(label)) {
        seen.add(label);
        hits.push({ line: i + 1, label: `possible secret (${label})` });
        break;
      }
    }
    for (const d of deny) {
      if (d.re.test(line) && !seen.has(`deny:${d.source}`)) {
        seen.add(`deny:${d.source}`);
        hits.push({ line: i + 1, label: `matches denyPatterns "${d.source}"` });
      }
    }
  });
  return hits;
}

/** Resolve a `related` entry: `group/slug` or a bare slug unique across item groups. */
export function resolveRelated(ref, items) {
  const r = String(ref).replace(/^\.?\//, '').replace(/\.md$/, '');
  const hits = items.filter((it) => `${it.group}/${it.slug}` === r || it.slug === r);
  return { ref: r, hits: [...new Set(hits)] };
}

export function validateDocs(docs, { repoRoot, config, configText = '' } = {}) {
  const cfg = resolveConfig(config);
  const problems = [];
  const items = docs.filter((d) => d.group);
  const cf = fillMarkers(configText);
  if (cf.length) problems.push(`overview.config.json: unfilled ${cf.join(', ')}`);
  for (const d of docs) {
    const { data, rel } = d;
    const text = d.text || '';
    const fills = fillMarkers(text);
    if (fills.length) problems.push(`${rel}: unfilled ${fills.join(', ')}`);
    for (const h of scanSecrets(text, cfg.deny)) problems.push(`${rel}:${h.line}: ${h.label}`);

    const g = d.group ?? '';
    const gc = g ? cfg.groups[g] || {} : {};
    const statuses = asList(gc.statuses);
    if (statuses.length && asList(data.status).length && !statuses.includes(data.status)) {
      problems.push(`${rel}: status "${data.status}" is not one of: ${statuses.join(', ')}`);
    }
    for (const f of asList(gc.required)) {
      const v = data[f];
      if (!(isObj(v) || asList(v).some((x) => String(x).trim()))) problems.push(`${rel}: missing required field \`${f}\` (group ${g})`);
    }
    for (const [k, allowed] of Object.entries(ENUMS)) {
      if (asList(data[k]).length && !allowed.includes(data[k])) problems.push(`${rel}: ${k} "${data[k]}" is not one of: ${allowed.join(', ')}`);
    }
    if (asList(data.confirmed).length && !(/^\d{4}-\d{2}-\d{2}$/.test(data.confirmed) && !Number.isNaN(Date.parse(data.confirmed)))) {
      problems.push(`${rel}: confirmed "${data.confirmed}" is not a YYYY-MM-DD date`);
    }
    for (const r of asList(data.related)) {
      const { ref, hits } = resolveRelated(r, items);
      if (hits.length === 0) problems.push(`${rel}: related "${ref}" does not match any item (use group/slug or a unique slug)`);
      else if (hits.length > 1) problems.push(`${rel}: related "${ref}" is ambiguous (${hits.map((h) => `${h.group}/${h.slug}`).join(', ')}); use group/slug`);
    }
    if (!repoRoot) continue;
    for (const p of asList(data.related_docs)) {
      if (/^[a-z][a-z0-9+.-]*:/i.test(p)) continue;
      if (!pathExists(repoRoot, String(p))) problems.push(`${rel}: related_docs "${p}" does not exist`);
    }
    for (const p of asList(data.paths)) {
      if (!pathExists(repoRoot, String(p))) problems.push(`${rel}: paths "${p}" does not exist`);
    }
  }
  return problems;
}

/** indexFields must be scalars or lists; a map value would silently vanish from INDEX.md. */
export function indexFieldWarnings(docs, { config } = {}) {
  const cfg = resolveConfig(config);
  const out = [];
  for (const d of docs) {
    for (const f of asList(cfg.groups[d.group ?? '']?.indexFields)) {
      if (isObj(d.data[f])) out.push(`${d.rel}: indexFields value \`${f}\` parsed as a map; use a scalar or a list`);
    }
  }
  return out;
}

const authorTodos = (text) => (stripComments(text || '').match(AUTHOR) || []).length;

/** Open `TODO(author)` markers per doc, outside HTML comments: [{ rel, count }]. Always informational. */
export function countAuthorTodos(docs) {
  return docs.map((d) => ({ rel: d.rel, count: authorTodos(d.text) })).filter((x) => x.count);
}

// ---------------------------------------------------------------------------
// Staleness. Default: commits touching `paths` after the doc's last commit.
// With mergeBase (PR mode): commits touching `paths` in mergeBase..HEAD, only
// when the doc itself has no commit in that range. Uncommitted changes in
// `paths` count in both. Every overview root and `staleIgnore` glob is excluded.
// Docs with uncommitted edits are skipped (treated as being updated).
// ---------------------------------------------------------------------------

export function findStale(docs, { repoRoot, excludeRoots = [], staleIgnore = DEFAULTS.staleIgnore, mergeBase = null }) {
  if (git(['rev-parse', '--is-inside-work-tree'], repoRoot) !== 'true') return { git: false, shallow: false, stale: [], skipped: [] };
  const shallow = git(['rev-parse', '--is-shallow-repository'], repoRoot) === 'true';
  const excludes = new Set();
  for (const r of excludeRoots) {
    const rel = toPosix(relative(repoRoot, r));
    if (rel && !rel.startsWith('..')) excludes.add(`:(exclude)${rel}`);
  }
  for (const p of staleIgnore) excludes.add(`:(exclude,glob)${p}`);
  const ex = [...excludes];
  const stale = [];
  const skipped = [];
  for (const d of docs) {
    const specs = asList(d.data.paths).map((p) => String(p).replace(/^\.?\//, '') || '.');
    if (!specs.length) continue;
    const docPath = toPosix(relative(repoRoot, d.file));
    if (git(['status', '--porcelain', '--', docPath], repoRoot)) { skipped.push(d.rel); continue; }
    let range;
    if (mergeBase) {
      range = `${mergeBase}..HEAD`;
      if (git(['log', '-1', '--format=%H', range, '--', docPath], repoRoot)) continue; // doc updated on this branch
    } else {
      const docCommit = git(['log', '-1', '--format=%H', '--', docPath], repoRoot);
      if (!docCommit) { skipped.push(d.rel); continue; }
      range = `${docCommit}..HEAD`;
    }
    const log = git(['log', '--format=%h%x09%s', range, '--', ...specs, ...ex], repoRoot) || '';
    const commits = log.split('\n').filter(Boolean).map((l) => {
      const [sha, ...subject] = l.split('\t');
      return { sha, subject: subject.join('\t') };
    });
    const dirty = (git(['status', '--porcelain', '--', ...specs, ...ex], repoRoot) || '').split('\n').filter(Boolean).length;
    if (commits.length || dirty) stale.push({ doc: d.rel, commits, dirty });
  }
  return { git: true, shallow, stale, skipped };
}

/**
 * Author intent due for reconfirm: author/mixed docs whose `confirmed` is older than `days`,
 * plus `source: author` docs never confirmed that have no open TODO(author) (those are still being written).
 */
export function findReconfirm(docs, { days = DEFAULTS.reconfirmAfterDays, now = Date.now() } = {}) {
  if (!days) return [];
  const out = [];
  for (const d of docs) {
    const src = d.data.source;
    if (src !== 'author' && src !== 'mixed') continue;
    const c = asList(d.data.confirmed).length ? String(d.data.confirmed) : null;
    if (c) {
      const t = Date.parse(`${c}T00:00:00Z`);
      const ageDays = Number.isNaN(t) ? null : Math.floor((now - t) / 86400000);
      if (ageDays === null || ageDays > days) out.push({ doc: d.rel, confirmed: c, ageDays });
    } else if (src === 'author' && !authorTodos(d.text)) {
      out.push({ doc: d.rel, confirmed: null, ageDays: null });
    }
  }
  return out;
}

// ---------------------------------------------------------------------------
// Root resolution
// ---------------------------------------------------------------------------

const isRootDir = (dir) => existsSync(join(dir, 'overview.config.json')) || basename(dir) === '.overview'
  || (basename(dir) === 'overview' && ['docs', '.config'].includes(basename(dirname(dir))));
const isDir = (p) => { try { return statSync(p).isDirectory(); } catch { return false; } };

/**
 * Every overview root under repoRoot (depth 4): folders with overview.config.json, or docs/overview, .overview, .config/overview.
 * `nested: true` also descends into roots (used to exclude every root from --stale).
 */
export function discoverRoots(repoRoot, { nested = false } = {}) {
  const found = [];
  const walk = (dir, depth) => {
    if (depth > SEARCH_DEPTH) return;
    if (isRootDir(dir)) { found.push(dir); if (!nested) return; }
    let ents;
    try { ents = readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const e of ents.sort((a, b) => byString(a.name, b.name))) {
      if (!e.isDirectory() || SKIP_DIRS.has(e.name)) continue;
      walk(join(dir, e.name), depth + 1);
    }
  };
  walk(repoRoot, 0);
  return found;
}

/**
 * Find the overview root for cwd. Returns { root } or { ambiguous: [dirs] }.
 * Order: walk up from cwd to repoRoot (an ancestor holding overview.config.json, or
 * <ancestor>/docs/overview, .overview, .config/overview); then down-search from repoRoot. Several hits with no
 * single shallowest one are ambiguous. Nothing found: <repoRoot>/docs/overview.
 * `downSearch: false` returns { needRoot: true } instead of searching down.
 */
export function resolveRoot(repoRoot, cwd = repoRoot, { downSearch = true } = {}) {
  let dir = cwd;
  for (;;) {
    if (existsSync(join(dir, 'overview.config.json'))) return { root: dir };
    const hit = ROOT_CANDIDATES.map((c) => join(dir, c)).find(isDir);
    if (hit) return { root: hit };
    if (dir === repoRoot || relative(repoRoot, dir).startsWith('..')) break;
    const up = dirname(dir);
    if (up === dir) break;
    dir = up;
  }
  if (!downSearch) return { needRoot: true };
  const found = discoverRoots(repoRoot);
  if (found.length <= 1) return { root: found[0] || join(repoRoot, DEFAULT_ROOT) };
  const depth = (d) => toPosix(relative(repoRoot, d)).split('/').length;
  const min = Math.min(...found.map(depth));
  const nearest = found.filter((d) => depth(d) === min);
  return nearest.length === 1 ? { root: nearest[0] } : { ambiguous: found };
}

