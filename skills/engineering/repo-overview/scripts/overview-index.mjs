#!/usr/bin/env node
/**
 * overview-index.mjs: generate, validate, and check INDEX.md for a modular repo overview.
 *
 * The overview is a folder of small markdown files with YAML frontmatter
 * (default: docs/overview/). INDEX.md is a one-line-per-file router that agents
 * read first, then open only the files they need. The format is documented in
 * SCHEMA.md so it can also be maintained by hand where Node is not available.
 *
 * Usage:
 *   node overview-index.mjs                     write INDEX.md (fails only on unreadable docs or missing summary)
 *   node overview-index.mjs --check             fail if INDEX.md is out of date or validation finds problems
 *   node overview-index.mjs --validate          validate frontmatter, links, markers, secrets only
 *   node overview-index.mjs --stale             list docs whose `paths` changed after the doc, and author docs to reconfirm
 *   node overview-index.mjs --stale --strict    same, exit 1 when any doc is stale
 *   node overview-index.mjs --stale --base REF  PR mode: docs whose `paths` changed since merge-base(REF, HEAD) with no doc update
 *   --root <dir>   overview folder (default: nearest one, see SCHEMA.md "Root resolution")
 *   --all          process every overview root found in the repo (monorepos)
 *
 * Exit codes: 0 ok, 1 problems found, 2 usage error or ambiguous root.
 * Config: optional <root>/overview.config.json (keys and defaults in SCHEMA.md).
 * Plain Node >= 18, zero dependencies. Exports pure helpers for tests.
 */
